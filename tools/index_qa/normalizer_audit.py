# -*- coding: utf-8 -*-
"""حارسُ المطبِّع — يقيس ما يفعله `words()` بألف الوصل قبل أن يُغيَّر سطرٌ فيه.

    python tools/index_qa/normalizer_audit.py --self-test
    python tools/index_qa/normalizer_audit.py            # جردُ الأصول بالرواية

## ⛔ الحقيقةُ التي يحرسها (‏مقيسةٌ 2026-09-07، جنديّ الفهرسة)

في `run.py` قاعدةُ طيٍّ مكتوبةٌ بنيّةٍ صريحة: `("ٱ", "ا")` — **وهي ميتةٌ لا
تعمل أبداً**، والعلّةُ ترتيبٌ لا منطق:

```python
_AR = re.compile(r"[^ء-ي ]")     # ء = U+0621 · ي = U+064A
_FOLD = (…, ("ٱ", "ا"), …)       # ٱ = U+0671 — **خارج المدى**
def words(t):
    … ; t = _AR.sub("", t) ; …   # ← يُحذف هنا
    for a, b in _FOLD: …         # ← فلا يبقى شيءٌ يُطوى
```

فألفُ الوصل تُمحى قبل أن يراها الطيّ: «ٱللَّهِ» تصير `لله` بينما يكتبها
التفريغُ `الله`. وسائرُ قواعد الطيّ سليمةٌ لأن مصادرها داخل المدى.

## الأثرُ مقيسٌ بالأسماء — لا يُقدَّر

**١) التعرّضُ في الأصول** (‏`--riwayat`): ألفُ الوصل في **حفصٍ وشعبةَ وحدهما**:

| الرواية | كلماتٌ تحوي `ٱ` | النسبة |
|---|---|---|
| حفص | 13,482 من 82,008 | **16.4%** |
| شعبة | 13,485 من 77,629 | **17.4%** |
| ورش · قالون · الدوري · السوسي | **0** | **0.0%** |

⇒ المطبِّعُ **غيرُ متماثلٍ بين الروايات**: يمسّ مرجعَ حفصٍ وشعبةَ ولا يمسّ غيرَهما.

**٢) الأثرُ على الأحكام** — أُعيد تشغيل `judge()` على صفوفٍ **حقيقيةٍ محفوظةٍ في
تقارير `audio_qa`** (‏فيها `heard` كما سُمع) بالمطبِّعَين:

| الفهرس | صفوف | جسيمٌ بالحاليّ | بالمطويّ | انقلابات |
|---|---|---|---|---|
| `mrifai` (حفص، ستّةُ ملوح) | 1200 | 3.75% | **3.83%** | 13 — **في الاتجاهين** |
| `mukhtar_haj` (حفص، ملحان) | 400 | 2.75% | 3.50% | 5 |
| `laghdaf_shinqiti` (ورش — **شاهدُ ضبط**) | 800 | 0.75% | **0.75%** | **صفر** |

⇒ **العطبُ ضجيجٌ لا انحياز**: لا يُمرّر بانتظامٍ ولا يردّ بانتظام، **ولم يعبر
حكمُ فهرسٍ واحدٍ عتبةَ 5% في الاتجاهين** في 2400 صفٍّ أُعيد تشغيلها. وشاهدُ
الضبط (ورش، وأصلُه بلا ألفِ وصل) **صفرُ انقلاب** — وهو ما يثبت أن السببَ ألفُ
الوصل بعينها لا تقلّبُ الأداة.

## ⇒ ولذلك **لم يُغيَّر السطر** (قرارُ جنديّ الفهرسة، يُرفع للمشرف)

طيُّ الوصل يجعل حفصاً وشعبةَ **يُحكمان بمسطرةٍ غير التي حُكم بها 143 مشهوداً**،
والمكسبُ المقيس **صفرُ أحكامٍ تتبدّل**. فالتغييرُ كلفةٌ بلا عائد — **حتى يبتّه
المشرف**. وهذا نصُّ الدرس العشرين: **لا يُشدَّد حارسٌ (‏ولا يُرخى) قبل أن يُقاس
أثرُه بالأسماء.**

## ⛔ وحيث يجب أن يُطوى قطعاً: **كاشفُ النسبة الخاطئة**

الحارسُ الثالث في `add_surah_reciter.py` يقابل تفريغَ الصوت بنصّ الرواية
المعلَنة وبنصّ حفص، **ويردّ من طابق حفصاً أكثر**. وبالمطبِّع الحاليّ يقيس
الفارقُ بين نصّي حفصٍ وورشٍ **22.4% من الكلمات** — وأربعةَ عشرَ من كل خمسةَ
عشرَ اختلافاً في الفاتحة **أثرُ ألفِ الوصل لا فرقُ رواية** (‏الفرقُ الحقيقيُّ
الوحيد فيها `مالك`/`ملك`). ⇒ **الكاشفُ على هذا المطبِّع يقيس رسمَ الأصل لا
الرواية**، فيلزمه `words_folded` أدناه — **وهو مكتوبٌ هنا كي يُستعمل، لا كي
يُوصى به** (‏درسُ «المعرفةُ التي لا تسكن مكانَ الاستعمال لا تحرس»).
"""
from __future__ import annotations

import argparse
import gzip
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

for _s in (sys.stdout, sys.stderr):
    try:
        _s.reconfigure(encoding="utf-8")
    except Exception:                                     # noqa: BLE001
        pass

WASLA = "ٱ"          # ٱ — ألفُ الوصل، خارج مدى `ء-ي`
RIWAYAT = ("hafs", "warsh", "qalun", "shuba", "douri", "sousi")


def words_folded(t: str):
    """المطبِّعُ الذي **يطوي ألفَ الوصل فعلاً** — الطيُّ قبل حذفِ ما خرج عن المدى.

    ⛔ لا يحلّ محلّ `run.words` في أحكام `audio_qa` (‏انظر ترويسة الملفّ)، وإنما
    يُستعمل حيث تُقابَل **روايةٌ برواية**: كاشفُ النسبة الخاطئة قبل كلّ شيء."""
    from run import _AR, _DROP, _FOLD, _SMALL
    t = t or ""
    for a, b in _SMALL:
        t = t.replace(a, b)
    for a, b in _FOLD:          # ← فوق `_AR` لا تحتَه: هنا الفرقُ كلُّه
        t = t.replace(a, b)
    t = _AR.sub("", t)
    t = t.replace(_DROP, "")
    return [w for w in t.split() if w]


def skel_folded(t: str) -> str:
    return "".join(words_folded(t))


def _self_test() -> None:
    from run import words
    # (١) القاعدةُ ميتةٌ في المطبِّع الحاليّ — تُثبَت لا تُوصف
    assert words("ٱللَّهِ") == ["لله"], words("ٱللَّهِ")
    assert words_folded("ٱللَّهِ") == ["الله"], words_folded("ٱللَّهِ")
    print("  ✅ (١) `words` تحذف ألفَ الوصل (`لله`) و`words_folded` تطويها (`الله`)")

    # (٢) وسائرُ قواعد الطيّ حيّةٌ — فالعلّةُ في هذه وحدَها لا في الترتيب كلِّه
    for src, want in (("أ", "ا"), ("إ", "ا"), ("آ", "ا"), ("ى", "ي"),
                      ("ة", "ه"), ("ؤ", "و"), ("ئ", "ي")):
        assert words(src + "ب") == [want + "ب"], (src, words(src + "ب"))
    print("  ✅ (٢) بقيّةُ قواعد الطيّ تعمل — العلّةُ في `ٱ` وحدَها (‏U+0671 خارج المدى)")

    # (٣) الفاتحة: أربعةَ عشرَ من خمسةَ عشرَ اختلافاً أثرُ الرسم لا الرواية
    h = "بِسْمِ ٱللَّهِ ٱلرَّحْمَٰنِ ٱلرَّحِيمِ"
    w = "بِسْمِ اِ۬للَّهِ اِ۬لرَّحْمَٰنِ اِ۬لرَّحِيمِ"
    assert words(h) != words(w), "بالمطبِّع الحاليّ يختلفان — وهو الإنذارُ الكاذب"
    assert words_folded(h) == words_folded(w), (words_folded(h), words_folded(w))
    print("  ✅ (٣) بسملةُ حفصٍ وورشٍ تتطابقان بالطيّ وتختلفان بدونه — الإنذارُ الكاذب مُبرهَن")

    # (٤) ولا يطوي ما ليس ألفَ وصلٍ: `مالك`/`ملك` فرقُ روايةٍ يبقى بعد الطيّ
    assert words_folded("مَٰلِكِ") != words_folded("مَلِكِ")
    print("  ✅ (٤) فرقُ الرواية الحقيقيّ (`مالك`/`ملك`) يبقى بعد الطيّ — الكاشفُ لا يُعمى")
    print("✅ --self-test أخضر · normalizer_audit-1.0")


def audit_assets() -> int:
    """جردُ التعرّض من أصول النصّ نفسِها — بصفرِ شبكة."""
    from run import ASSETS
    print(f"{'الرواية':<8} {'كلماتٌ تحوي ٱ':>14} {'من':>9} {'النسبة':>9}")
    bad = 0
    for r in RIWAYAT:
        p = ASSETS / f"text_{r}.jz"
        if not p.exists():
            print(f"{r:<8} {'—':>14}  (لا أصلَ على القرص)")
            continue
        t = json.loads(gzip.decompress(p.read_bytes()).decode("utf-8"))
        toks = " ".join(t).split()
        aff = sum(1 for x in toks if WASLA in x)
        pct = 100 * aff / max(len(toks), 1)
        flag = "  ⛔" if aff else ""
        if aff:
            bad += 1
        print(f"{r:<8} {aff:>14,} {len(toks):>9,} {pct:>8.1f}%{flag}")
    print(f"\n⇒ رواياتٌ يمسّها المطبِّع: {bad} من {len(RIWAYAT)} — والباقي بلا أثر.")
    return bad


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--self-test", action="store_true")
    a = ap.parse_args()
    if a.self_test:
        _self_test()
        return
    audit_assets()


if __name__ == "__main__":
    main()
