#!/usr/bin/env python3
"""اختبارُ الحارسِ على الحارس — أثرُ الإسقاط المعلَن في بصمات الصوت.

⛔⛔ **الحالةُ المقيسة 2026-09-20** (`asim`، سورةُ ص غائبةٌ عند الناشر بـ404):
الفهرسُ نفسُه سليم (`qa.fatal=None` · تغطية 0.9856 · `transform.op='drop_surah:38'`)
وأحكامُه الحديثةُ الأربعةُ بلا فاتلٍ واحد. ومع ذلك لا شهادة — لأنّ أحكاماً
**متقادمةً** على البصمة نفسِها (`k1..k4`، سابقةً لإصلاح `run.py`) تحمل الفاتل:
    «بصمات الصوت 113/114 — سورٌ بلا برهان تنزيل»
وهو **أثرُ الإسقاط المعلَن عينُه**: سورةٌ حُذفت بإعلانٍ ⇒ بصمتُها غائبةٌ لزوماً.
فلم تُدرجه `DECLARED_DROP_FATALS` فعُدّ عطباً غيرَ معلَنٍ وسقطت الشهادة.

⭐⭐ **والدرس: حارسٌ عُلِّم بعضَ آثارِ الحالة المعذورة يردُّ الحالةَ المعذورة
نفسَها متى ظهرت بأثرٍ لم يُعلَّمه** — فالنقصُ في تعليمه لا في المادّة.

⛔ **وهذا التعديلُ يجب ألّا يُضعف الحارسَ**، ولذا تُثبِّت هذه الاختباراتُ أنّ
العفوَ **مشروطٌ بالإعلان وحدَه**: بلا `drop_surah` يبقى الفاتلُ رادّاً، ويبقى
كلُّ فاتلٍ آخرَ رادّاً ولو مع الإعلان.
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from certify_catalog import undeclared_fatal  # noqa: E402

SHA_FATAL = "بصمات الصوت 113/114 — سورٌ بلا برهان تنزيل"
AUDIO_FATAL = "بسملة مبتلعة في 37:1"
DROP = "drop_surah:38"

CASES = [
    # (الفواتل، الإسقاط، أيُردّ؟، لماذا)
    ([], "", False, "① لا فاتلَ ⇒ لا ردّ"),
    ([SHA_FATAL], DROP, False,
     "② أثرُ البصمة مع إعلانٍ ⇒ يُعفى — وهو عينُ حالة asim"),
    ([SHA_FATAL], "", True,
     "③ ⛔ أثرُ البصمة **بلا إعلان** ⇒ يبقى رادّاً — وإلا صار الحارسُ أضعف"),
    ([AUDIO_FATAL], DROP, True,
     "④ ⛔ فاتلٌ صوتيٌّ حقيقيٌّ مع إعلانٍ ⇒ يبقى رادّاً — فالإعلانُ يعفو عن "
     "أثرِ الحذف لا عن عطبِ التلاوة (‏وهي علّةُ koshi_warsh عينُها)"),
    ([SHA_FATAL, AUDIO_FATAL], DROP, True,
     "⑤ ⛔ معذورٌ **مع** حقيقيٍّ ⇒ يُردّ — فلا يُخبَّأ عطبٌ خلف إعلان"),
    (["سور غائبة كلياً: [38]"], DROP, False, "⑥ الآثارُ القديمةُ باقيةٌ تعمل"),
    (["سور غائبة كلياً: [38]"], "", True, "⑦ وهي أيضاً تُردّ بلا إعلان"),
    ([SHA_FATAL], "realign:12", True,
     "⑧ ⛔ تحويلٌ ليس إسقاطاً ⇒ لا عفوَ (‏العفوُ لـdrop_surah وحدَه)"),
]


def main():
    bad = 0
    for fatals, op, want, why in CASES:
        got = undeclared_fatal(fatals, op)
        ok = got == want
        bad += not ok
        print(f"{'✅' if ok else '❌'} {why}\n      ⇒ يُردّ={got} والمنتظَر={want}")
    print(f"\n{'✅' if not bad else '❌'} {len(CASES) - bad}/{len(CASES)}")
    return 1 if bad else 0


if __name__ == "__main__":
    raise SystemExit(main())
