#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""يُزيح حدودَ مخرَجِ محاذاةٍ بمقدارٍ معلومٍ إلى إحداثيّات الملفّ الأصلي.

    python tools/index_qa/shift_entries.py work/s108.json 4200

⛔ **وليس هذا «الطرحَ الثابت» المرفوض** (‏قاعدةٌ من واقعة `deban_douri`):
المرفوضُ أن **تُزاح حدودٌ قائمةٌ** بمقدارٍ مقدَّرٍ لتصحيحِ بسملةٍ مبتلعة —
فالعلّةُ هناك أن المحاذي لم يتعرّف البسملة، ومقدارُ الإزاحة **مجهول**، ومن
طرح 460 م.ث جعل المدخلَ يبدأ من رأس الملفّ فابتلعها كاملة.

**وهذا عكسُه:** الصوتُ **قُصّ فعلاً** قبل المحاذاة عند نقطةٍ **مقيسة**، فحدودُ
المخرَج بإحداثيّات المقطع لا الأصل، وإعادتُها **حسابٌ لا تقدير**: كلُّ حدٍّ
`+ نقطةُ البدء` بالضبط. والبرهانُ أن الإزاحة صحيحة هو **فحصُ المطالع والعيّنة
الصوتية بعدها** — لا هذا السطر.
"""
import json
import sys


def main() -> None:
    if len(sys.argv) != 3:
        sys.exit("الاستعمال: shift_entries.py <ملف.json> <مقدار م.ث>")
    path, off = sys.argv[1], int(sys.argv[2])
    if off <= 0:
        sys.exit("⛔ المقدارُ يجب أن يكون موجباً — والصفرُ لا يُستدعى أصلاً")
    d = json.load(open(path, encoding="utf-8"))
    n = 0
    for e in d.get("entries") or []:
        for k in ("startMs", "endMs"):
            if e.get(k) is not None:
                e[k] = int(e[k]) + off
                n += 1
    d["shiftedBy"] = off          # أثرٌ في المخرَج: من قرأه علم أنه أُزيح
    json.dump(d, open(path, "w", encoding="utf-8"), ensure_ascii=False)
    print(f"  أُزيح {n} حدّاً بمقدار +{off} م.ث إلى إحداثيّات الأصل")


if __name__ == "__main__":
    main()
